/**
 * Custom Cloudflare Worker entrypoint.
 *
 * OpenNext generates `.open-next/worker.js` as the real Next.js request
 * handler. We wrap it with DataFast's crawler tracking (the sanctioned
 * Cloudflare Workers pattern from https://datafa.st/docs/bot-traffic-tracking)
 * so server-side bot-traffic tracking runs on every request.
 *
 * We can't use Next.js `proxy`/middleware for this: Next 16 proxy is
 * Node-runtime only and OpenNext's Cloudflare adapter rejects Node middleware
 * ("Node.js middleware is not currently supported"). And `functions/_middleware.ts`
 * only runs on Cloudflare Pages — this app deploys as a Worker via OpenNext.
 *
 * It also serves Markdown for Agents: a GET with `Accept: text/markdown` gets
 * the page converted to Markdown by Workers AI `toMarkdown` (the same engine
 * as Cloudflare's zone-level "Markdown for Agents" toggle, which needs a Pro
 * plan). Browsers never send that Accept value, so they still get HTML.
 *
 * This file is bundled by Wrangler, not by `next build`, so it is excluded
 * from the Next.js TypeScript project (see tsconfig.json). Types are kept
 * self-contained to avoid pulling in @cloudflare/workers-types.
 */
import { trackAICrawlerResponse } from "@datafast/ai-crawl";
// @ts-expect-error - generated by `opennextjs-cloudflare build`
import openNextWorker from "./.open-next/worker.js";

// Re-export any Durable Object classes OpenNext bundles (cache/queue), so
// Wrangler bindings that reference them keep resolving.
// @ts-expect-error - generated by `opennextjs-cloudflare build`
export * from "./.open-next/worker.js";

type MarkdownResult =
  | { format: "markdown"; data: string; tokens: number }
  | { format: "error"; error: string };

type Env = {
  // Optional Bot traffic token (dfbot_...). Set it as a Worker secret:
  // `wrangler secret put DATAFAST_BOT_TOKEN`. Never commit it.
  DATAFAST_BOT_TOKEN?: string;
  // Workers AI binding (wrangler.jsonc `ai`). HTML conversion is free.
  AI: {
    toMarkdown(
      file: { name: string; blob: Blob },
      options?: { conversionOptions?: { html?: { hostname?: string } } },
    ): Promise<MarkdownResult>;
  };
};

// Same policy as the Content-Signal lines in public/robots.txt.
const CONTENT_SIGNAL = "ai-train=yes, search=yes, ai-input=yes";

type ExecutionContext = { waitUntil(promise: Promise<unknown>): void };

// Same behavior as DataFast's `withAICrawlerTracking`: run the OpenNext
// handler, then report the crawler request + response status to DataFast in
// the background via ctx.waitUntil. It never blocks or buffers the response
// body. We call `trackAICrawlerResponse` directly because the token lives on
// the per-request `env`, and the wrapper only takes a static config.
async function fetch(
  request: Request,
  env: Env,
  ctx: ExecutionContext,
): Promise<Response> {
  const response: Response = await openNextWorker.fetch(request, env, ctx);

  trackAICrawlerResponse(request, response, ctx, {
    websiteId: "dfid_g2ojbeIQME0i1UQ8TRicK",
    authToken: env.DATAFAST_BOT_TOKEN,
  });

  if (!isHtml(response)) return response;
  if (request.method === "GET" && wantsMarkdown(request)) {
    return toMarkdownResponse(request, response, env);
  }
  // HTML and Markdown share a URL, so caches must key on Accept.
  const html = new Response(response.body, response);
  html.headers.append("Vary", "Accept");
  return html;
}

function isHtml(response: Response): boolean {
  return (response.headers.get("Content-Type") ?? "").includes("text/html");
}

// True when the Accept header lists text/markdown without `q=0`.
function wantsMarkdown(request: Request): boolean {
  return (request.headers.get("Accept") ?? "").split(",").some((part) => {
    const [type, ...params] = part.split(";").map((p) => p.trim().toLowerCase());
    return type === "text/markdown" && !params.some((p) => /^q=0(\.0*)?$/.test(p));
  });
}

// Converts an HTML response to Markdown, keeping the original status and
// headers (like Cloudflare's Markdown for Agents). Falls back to the HTML if
// conversion fails, so an AI outage never breaks the page.
async function toMarkdownResponse(
  request: Request,
  response: Response,
  env: Env,
): Promise<Response> {
  const html = await response.text();
  const headers = new Headers(response.headers);
  headers.append("Vary", "Accept");

  try {
    const result = await env.AI.toMarkdown(
      { name: "page.html", blob: new Blob([html], { type: "text/html" }) },
      { conversionOptions: { html: { hostname: new URL(request.url).origin } } },
    );
    if (result.format !== "markdown") throw new Error(result.error);

    headers.set("Content-Type", "text/markdown; charset=utf-8");
    headers.set("x-markdown-tokens", String(result.tokens));
    if (!headers.has("Content-Signal")) headers.set("Content-Signal", CONTENT_SIGNAL);
    // These describe the HTML body, not the Markdown one.
    for (const name of ["Content-Length", "Content-Encoding", "ETag", "Last-Modified"]) {
      headers.delete(name);
    }
    return new Response(result.data, { status: response.status, headers });
  } catch (error) {
    console.error("Markdown conversion failed", request.url, error);
    return new Response(html, { status: response.status, headers });
  }
}

const handler = { fetch };
export default handler;
