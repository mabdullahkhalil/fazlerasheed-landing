/**
 * `/.well-known/search`: Search for Agents, served by worker.ts.
 *
 * Contract (https://developers.cloudflare.com/ai-search/how-to/search-for-agents/):
 * - `GET /.well-known/search?q=...`
 * - `QUERY /.well-known/search` (RFC 10008) with a `text/plain` body or a
 *   JSON body `{"q": "..."}`
 * - The response is Markdown: retrieved passages with their source and a
 *   relevance score. It is not a generated answer.
 *
 * Ranking is BM25 over a prebuilt inverted index
 * (scripts/generate-search-index.ts), so a query only walks the postings of
 * its own terms. Like worker.ts, this file is bundled by Wrangler and is
 * excluded from the Next.js TypeScript project.
 */
// @ts-expect-error - generated by `bun run build` (scripts/generate-search-index.ts)
import index from "./.next/agent-search-index.json";
import { AGENT_SEARCH, AGENT_SEARCH_PATH } from "./src/lib/agent-search";
import { tokenize } from "./src/lib/search-tokenize";

type Passage = { path: string; title: string; heading: string; text: string };
type SearchIndex = {
  base: string;
  passages: Passage[];
  lengths: number[];
  avgLength: number;
  // term -> flat [passageIndex, termFrequency, ...] pairs
  postings: Record<string, number[]>;
};

const DEFAULT_LIMIT = 5;
const MAX_LIMIT = 10;
const MAX_PER_PAGE = 2;
const MAX_QUERY_LENGTH = 500;
const ACCEPT_QUERY = "text/plain, application/json, application/x-www-form-urlencoded";
const CONTENT_SIGNAL = "ai-train=yes, search=yes, ai-input=yes";

export function isSearchRequest(request: Request): boolean {
  return new URL(request.url).pathname === AGENT_SEARCH_PATH;
}

export async function handleSearch(request: Request): Promise<Response> {
  const method = request.method.toUpperCase();
  if (method === "OPTIONS") return new Response(null, { status: 204, headers: baseHeaders() });
  if (!["GET", "HEAD", "QUERY"].includes(method)) {
    return markdown(`# Method not allowed\n\nUse GET or QUERY.\n\n${usage()}`, 405);
  }

  const url = new URL(request.url);
  let query = url.searchParams.get("q") ?? "";
  if (method === "QUERY") {
    const parsed = await readQueryBody(request);
    if (parsed instanceof Response) return parsed;
    query = parsed;
  }
  query = query.trim().slice(0, MAX_QUERY_LENGTH);
  if (!query) return markdown(`# Missing query\n\n${usage()}`, 400);

  const limit = clamp(Number(url.searchParams.get("limit")) || DEFAULT_LIMIT, 1, MAX_LIMIT);
  const body = renderResults(query, search(query, limit));
  return markdown(body, 200, method === "HEAD");
}

// QUERY bodies: `text/plain` is the query itself; JSON is `{"q": "..."}`.
// `curl --data` sends a raw body labelled as a form, so a form body is read
// as `q=...` when it has that field and as plain text otherwise.
async function readQueryBody(request: Request): Promise<string | Response> {
  const type = (request.headers.get("Content-Type") ?? "text/plain").split(";")[0].trim().toLowerCase();
  const text = await request.text();
  if (type === "text/plain") return text;
  if (type === "application/x-www-form-urlencoded") {
    return /^q=/.test(text) ? (new URLSearchParams(text).get("q") ?? "") : text;
  }
  if (type === "application/json") {
    try {
      const json: unknown = JSON.parse(text);
      const q = (json as { q?: unknown })?.q;
      if (typeof q === "string") return q;
    } catch {
      /* fall through */
    }
    return markdown(`# Invalid JSON body\n\nSend \`{"q": "your query"}\`.\n\n${usage()}`, 400);
  }
  return markdown(`# Unsupported media type\n\nSend \`text/plain\` or \`application/json\`.\n\n${usage()}`, 415);
}

// ── Ranking ────────────────────────────────────────────────────────────────

type Ranked = { passage: Passage; score: number };

function search(query: string, limit: number): Ranked[] {
  const { passages, lengths, avgLength, postings } = index as SearchIndex;
  const k1 = 1.2;
  const b = 0.75;
  const scores = new Map<number, number>();
  for (const term of new Set(tokenize(query))) {
    const list = Object.hasOwn(postings, term) ? postings[term] : undefined;
    if (!list) continue;
    const n = list.length / 2;
    const idf = Math.log(1 + (passages.length - n + 0.5) / (n + 0.5));
    for (let i = 0; i < list.length; i += 2) {
      const doc = list[i];
      const freq = list[i + 1];
      const tf = (freq * (k1 + 1)) / (freq + k1 * (1 - b + (b * lengths[doc]) / avgLength));
      scores.set(doc, (scores.get(doc) ?? 0) + idf * tf);
    }
  }
  const ranked: Ranked[] = [...scores].map(([doc, score]) => ({ passage: passages[doc], score }));
  ranked.sort((x, y) => y.score - x.score);

  // Keep results varied: at most MAX_PER_PAGE passages from one page.
  const perPage = new Map<string, number>();
  const results: Ranked[] = [];
  for (const r of ranked) {
    const count = perPage.get(r.passage.path) ?? 0;
    if (count >= MAX_PER_PAGE) continue;
    perPage.set(r.passage.path, count + 1);
    results.push(r);
    if (results.length === limit) break;
  }
  // Scores are relative to the best match (1.000), as in Cloudflare's output.
  const top = results[0]?.score ?? 1;
  return results.map((r) => ({ ...r, score: r.score / top }));
}

// ── Output ─────────────────────────────────────────────────────────────────

function renderResults(query: string, results: Ranked[]): string {
  const { base } = index as SearchIndex;
  const lines = [`# Search results for: "${query.replace(/\s+/g, " ")}"`, ""];
  if (results.length === 0) {
    lines.push(
      "No matching content. Try different keywords, or read the site overview at",
      `${base}/llms.txt.`,
      "",
    );
  }
  for (const { passage, score } of results) {
    lines.push(
      `## ${passage.path} (score: ${score.toFixed(3)})`,
      "",
      `Source: ${base}${passage.path === "/" ? "/" : passage.path}`,
      `Page: ${passage.title}`,
      passage.heading !== passage.title ? `Section: ${passage.heading}` : "",
      "",
      // Inner headings become bold so they don't break the result structure.
      passage.text.replace(/^#{1,6} (.+)$/gm, "**$1**"),
      "",
    );
  }
  lines.push(
    "---",
    "",
    `Full pages are available as Markdown: request any Source URL with \`Accept: text/markdown\`.`,
    "",
  );
  return lines.filter((line, i, all) => line !== "" || all[i - 1] !== "").join("\n");
}

function usage(): string {
  return [
    "## Usage",
    "",
    "```",
    `GET ${AGENT_SEARCH.endpoint.replace("{query}", "battery+regeneration")}`,
    "",
    `QUERY ${AGENT_SEARCH_PATH}`,
    "Content-Type: application/json",
    "",
    '{"q": "Which lithium forklift batteries do you sell?"}',
    "```",
    "",
    `Optional: \`limit\` (1-${MAX_LIMIT}, default ${DEFAULT_LIMIT}).`,
    "",
    `Documentation: ${AGENT_SEARCH.documentation}`,
    "",
  ].join("\n");
}

function baseHeaders(): Headers {
  return new Headers({
    Allow: "GET, HEAD, QUERY, OPTIONS",
    // RFC 10008: the media types this resource accepts in QUERY requests.
    "Accept-Query": ACCEPT_QUERY,
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "GET, HEAD, QUERY, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Content-Signal": CONTENT_SIGNAL,
  });
}

function markdown(body: string, status: number, headOnly = false): Response {
  const headers = baseHeaders();
  headers.set("Content-Type", "text/markdown; charset=utf-8");
  // The index only changes on deploy. QUERY responses are not cached by
  // shared caches anyway (their key would need the body).
  headers.set("Cache-Control", status === 200 ? "public, max-age=3600" : "no-store");
  headers.set("X-Robots-Tag", "noindex");
  return new Response(headOnly ? null : body, { status, headers });
}

function clamp(n: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, Math.floor(n)));
}
